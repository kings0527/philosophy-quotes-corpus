FIELDS = ["传统", "人物", "派别", "①界线", "①关系", "②不动层",
          "③先验", "③秩序来源", "④互动", "④可改变", "④干预"]


def load_corpus():
    with io.open(os.path.join(ROOT, "统计总表.csv"), encoding="utf-8-sig") as fp:
        return list(csv.DictReader(fp))


def main():
    rows = load_corpus()
    missing = [r["人物"] for r in rows if r["人物"] not in COORD]
    if missing:
        raise SystemExit("坐标缺失：" + "、".join(missing))
    out = []
    for r in rows:
        c = COORD[r["人物"]]
        out.append([r["传统"], r["人物"], r["派别"]] + list(c))
    order = {"中国哲学": 0, "西方哲学": 1, "印度哲学": 2, "伊斯兰与波斯": 3, "日本哲学": 4}
    out.sort(key=lambda x: (order.get(x[0], 9), FIXED.index(x[5])))
    with io.open(os.path.join(ROOT, "坐标表.csv"), "w", encoding="utf-8-sig", newline="") as fp:
        w = csv.writer(fp)
        w.writerow(FIELDS)
        w.writerows(out)
    print("已写出 坐标表.csv：%d 人 × %d 列" % (len(out), len(FIELDS)))

    from collections import Counter
    for i, name in [(3, "①界线"), (4, "①关系"), (5, "②不动层"), (6, "③先验"),
                    (7, "③秩序来源"), (8, "④互动"), (9, "④可改变"), (10, "④干预")]:
        cnt = Counter(r[i] for r in out)
        print("%-8s  %s" % (name, " ｜ ".join("%s %d" % (k, v) for k, v in cnt.most_common())))


if __name__ == "__main__":
    main()
